import math, sys
bad = []
def ok(name, got, want, rel=0.02):
    if abs(got - want) > rel * max(abs(want), 1e-30):
        bad.append(f"{name}: 계산 {got:.6g} ≠ 본문 {want:.6g}")

e = 1.6e-19
# 파트 1
