J = 2.0 / (math.pi * 1e-6); E = 1.7e-8 * J
ok("응2-2 J", J, 6.37e5); ok("응2-2 E", E, 1.1e-2, .05); ok("응2-2 dV", E * 100, 1.1, .05); ok("응2-2 R", E * 100 / 2.0, 0.54)
ok("응2-2 검산 R", 1.7e-8 * 100 / (math.pi * 1e-6), 0.54)
