ok("응1-1 neA", neA, 5.44e4); vd = 0.50 / neA
ok("응1-1 v_d", vd, 9.2e-6); ok("응1-1 1 m 시간", 1.0 / vd, 1.1e5, .05)
ok("응1-2 J1", 2.0 / (math.pi * 1e-6), 6.4e5); ok("응1-2 J2", 2.0 / (math.pi * 0.25e-6), 2.5e6)
ok("응1-2 비", (1.0 / 0.5) ** 2, 4)
ok("개념 구리 v_d", 1.0 / (8.5e28 * e * 1e-6), 7e-5, .06)
