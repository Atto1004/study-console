# 파트 5 — 예제와 응용 5-1은 연립방정식을 직접 푼다
def solve(e1, e2, r1, r2, r3):
    # e1 - r1 i1 - r3 (i1+i2) = 0 ; e2 - r2 i2 - r3 (i1+i2) = 0
    a, b, c = r1 + r3, r3, e1
    d, f, g = r3, r2 + r3, e2
    D = a * f - b * d
    return (c * f - b * g) / D, (a * g - c * d) / D
i1, i2 = solve(10, 5, 2, 2, 4); ok("예제 i1", i1, 2.0); ok("예제 i2", i2, -0.50); ok("예제 i3", i1 + i2, 1.5)
